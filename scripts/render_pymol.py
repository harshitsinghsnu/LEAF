"""Render the three real best-found lipid conformers (PDB files already
generated by embed_3d.py via RDKit ETKDG+MMFF94 in the main project env)
as PyMOL ball-and-stick images. Runs inside the isolated pymol_env conda
environment -- no connection to the project's numpy/sklearn/RDKit stack.
"""
import os
import pymol
from pymol import cmd

pymol.finish_launching(["pymol", "-qc"])

BASE = os.path.join("results", "pdb_structures")
OUT = os.path.join("figures", "paper")
os.makedirs(OUT, exist_ok=True)

labels = {
    "leaf_llm_v3scored": "llama8b_scored",
    "static_ga": "static_ga",
    "random_search": "random_search",
}

for key, short in labels.items():
    pdb_path = os.path.join(BASE, f"{key}.pdb")
    cmd.reinitialize()
    cmd.load(pdb_path, "mol")
    cmd.hide("everything")
    cmd.show("sticks", "mol")
    cmd.show("spheres", "mol")
    cmd.set("sphere_scale", 0.18)
    cmd.set("stick_radius", 0.12)
    cmd.util.cbaw("mol")
    cmd.bg_color("white")
    cmd.set("ray_opaque_background", 1)
    cmd.set("antialias", 2)
    cmd.set("ray_trace_mode", 1)
    cmd.orient("mol")
    cmd.zoom("mol", buffer=2.0)
    out_png = os.path.join(OUT, f"fig5_pymol_{short}.png")
    cmd.ray(1200, 1000)
    cmd.png(out_png, dpi=300)
    print("wrote", out_png)
